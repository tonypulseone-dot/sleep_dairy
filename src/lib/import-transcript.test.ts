test('график-полоски и статистика: времени нет — снов нет, выдумывать не из чего', () => {
  const chart = sleepsFromTranscript(`Статистика
Сегодня >
[ПЛАШКА] 02 04 06 08 10 12 14 16 18 20 22
7 ч 23 мин | 2 ч 57 мин | 12 ч 21 мин
6 раз ночью | 4 раза днём | Бодрствование`, '2026-04-15');
  assert.equal(chart?.screen, 'chart');
  assert.deepEqual(chart?.sleeps, []);
  const stats = sleepsFromTranscript(`27 мая 2025 | 07 июн. 2025
[ПЛАШКА] Сон / Длительность | Сон / Время
13ч | 13ч | 12ч
5м | 6м | 55м
Минимум: 11ч 58м | Среднее: 12ч 49м | Максимум: 13ч 21м`, '2026-09-26');
  assert.equal(stats?.screen, 'stats');
  assert.deepEqual(stats?.sleeps, []);
});

