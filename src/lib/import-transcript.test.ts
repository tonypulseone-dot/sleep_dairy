test('отчёт с AM/PM: потерянные пометки не угадываем молча — «проверьте»', () => {
  const result = sleepsFromTranscript('07.10.26 | Дневной сон\n8:40—9:35 AM | 55 мин\n1:47—3:00 | 1 ч 13 мин', '2026-10-22');
  const lost = result?.sleeps.find((sleep) => sleep.start === '01:47');
  assert.equal(lost?.doubtful, true);
  assert.equal(result?.sleeps.find((sleep) => sleep.start === '08:40')?.doubtful, false);
});

test('даты с годом двумя цифрами', () => {
  assert.deepEqual(datesIn('10.10.26 | Дневной сон', '2026-10-22'), [{ date: '2026-10-10', hasYear: true }]);
  assert.deepEqual(datesIn('Период 10–17.10.2026', '2026-10-22'), [{ date: '2026-10-17', hasYear: true }]);
});

