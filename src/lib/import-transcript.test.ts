test('кормления и бодрствование с диапазонами — не сны', () => {
  assert.deepEqual(list(`12.08.2026\nКормление | 11:00 - 11:20\nСон | 11:30 - 12:10`, '2026-08-13'), ['2026-08-12 11:30-12:10']);
});

test('незнакомый формат: время есть, а правила не собрали — отдаём нейросети', () => {
  assert.equal(sleepsFromTranscript('Уснул в 13:05, проснулся в 14:20', '2026-08-13'), null);
});

test('даты: «12 авг. 2026», «11.08.2026», «Вчера», без года — не в будущем', () => {
  assert.deepEqual(datesIn('12 авг. 2026, ср | 26 авг.', '2026-08-26').map((d) => d.date), ['2026-08-12', '2026-08-26']);
  assert.deepEqual(datesIn('ВЧЕРА (ПОНЕДЕЛЬНИК) 03.08.2026', '2026-08-04').map((d) => d.date), ['2026-08-03', '2026-08-03']);
  assert.deepEqual(datesIn('28 декабря', '2026-01-05').map((d) => d.date), ['2025-12-28']);
});

// Второй ответ живого GigaChat на ту же ленту: строки склеены, два времени (17:40, 13:20) потеряны.
test('лента с потерянными временами: начало восстанавливается из длительности и сверяется с бодрствованием', () => {
  const transcript = `[ПЛАШКА] 12 авг. 2026, ср | 26 авг.
[ПЛАШКА] 13 авг | 12 авг
07:02, 13 авг | 1 час 58 минут
[ПЛАШКА] [солнце] 9 часов 52 минуты | 4
21:10 | 2 часа 49 минут
[ПЛАШКА] [солнце] 41 минута | 3
18:21 | 2 часа 45 минут
[ПЛАШКА] * 1 час 35 минут | 2
14:55 | 2 часа 33 минуты
[ПЛАШКА] * 42 минуты | 1
10:47 | 2 часа 17 минут
10:05
07:48`;
  const result = sleepsFromTranscript(transcript, '2026-08-26');
  assert.deepEqual(
    result?.sleeps.map((sleep) => `${sleep.date} ${sleep.start}-${sleep.end}${sleep.doubtful ? ' ?' : ''}`),
    ['2026-08-12 10:05-10:47', '2026-08-12 13:20-14:55', '2026-08-12 17:40-18:21', '2026-08-12 21:10-07:02'],
  );
});
