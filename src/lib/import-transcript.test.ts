test('даты: «12 авг. 2026», «11.08.2026», «Вчера», без года — не в будущем', () => {
  assert.deepEqual(datesIn('12 авг. 2026, ср | 26 авг.', '2026-08-26').map((d) => d.date), ['2026-08-12', '2026-08-26']);
  assert.deepEqual(datesIn('ВЧЕРА (ПОНЕДЕЛЬНИК) 03.08.2026', '2026-08-04').map((d) => d.date), ['2026-08-03', '2026-08-03']);
  assert.deepEqual(datesIn('28 декабря', '2026-01-05').map((d) => d.date), ['2025-12-28']);
});

