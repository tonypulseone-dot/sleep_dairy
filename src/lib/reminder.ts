import { plural } from '@/lib/pro-format';
import { QUIET_AFTER_DAYS } from '@/lib/pro-stats';
import { childWords, type ChildSex } from '@/lib/words';

/**
 * Готовый текст напоминания — Виктория копирует его в переписку с мамой.
 *
 * Тон зависит от того, сколько дней мама молчит, и число в тексте то же,
 * что в строке «последняя запись N дней назад» над кнопкой: напоминание
 * появляется с QUIET_AFTER_DAYS дней, и первое сообщение — самое мягкое.
 *
 * `silentDays` — сколько дней назад была последняя запись; null — записей
 * ещё не было, тогда считаем от подключения (`withUsDays`).
 */
export function reminderText(
  parentName: string | null,
  silentDays: number | null,
  withUsDays: number,
  sex: ChildSex | null = null,
): string {
  const words = childWords(sex);
  // Пишем как Виктория в мессенджере: без длинных тире и «ёлочек», обычными
  // словами. Типографика «как в книге» в переписке выдаёт шаблон.
  const hello = parentName ? `${parentName}, здравствуйте!` : 'Здравствуйте!';
  const days = (n: number) => `${n} ${plural(n, 'день', 'дня', 'дней')}`;
  const backdate = 'Пропущенные сны можно внести задним числом, на главном экране есть кнопка "Внести сон вручную".';

  if (silentDays === null) {
    // Подключилась, но не записала ни одного сна.
    if (withUsDays <= QUIET_AFTER_DAYS + 1) {
      return `${hello} Как у вас дела? Вижу, что дневник сна пока пустой. Получилось открыть приложение? Если что-то не выходит, напишите, помогу. Достаточно нажимать "${words.fellAsleep}" и "${words.wokeUp}", остальное приложение посчитает само.`;
    }
    return `${hello} Вы подключились к дневнику сна ${days(withUsDays)} назад, но записей пока нет. Всё в порядке? Если приложение неудобное или что-то не получается, напишите, разберёмся вместе. Начать можно с сегодняшнего дня. А если помните, как спал малыш вчера, это тоже можно внести задним числом, кнопкой "Внести сон вручную" на главном экране.`;
  }

  if (silentDays <= QUIET_AFTER_DAYS) {
    // Пропущен один день: лёгкое напоминание, без тревоги.
    return `${hello} Вижу, что вчера в дневнике сна не было записей. Всё в порядке? Если просто не успели отметить, ничего страшного. ${backdate}`;
  }
  if (silentDays <= 4) {
    return `${hello} Как у вас дела? Последняя запись в дневнике сна была ${days(silentDays)} назад. Если отмечать неудобно, напишите, подскажу, как проще. ${backdate}`;
  }
  if (silentDays <= 9) {
    return `${hello} Как вы? В дневнике сна уже ${days(silentDays)} без записей, и мне сложно видеть, как идёт режим. Давайте продолжим? Если не получается отмечать каждый сон, можно вносить сны один раз вечером за весь день. ${backdate}`;
  }
  return `${hello} Давно не виделись в дневнике сна, последняя запись была ${days(silentDays)} назад. Как вы и малыш? Если нужна пауза или консультация сейчас не актуальна, просто напишите, я пойму. А если хотите продолжить, начнём с сегодняшнего дня.`;
}
