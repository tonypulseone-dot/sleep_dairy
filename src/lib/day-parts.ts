/**
 * Часть суток словами: так мама и думает о дне — «утренний сон», «вечером
 * не уснёт». Цифры 0/6/12/18 читались как техника, а не как её день.
 */
export function partOfDay(hour: number): 'утро' | 'день' | 'вечер' | 'ночь' {
  if (hour >= 5 && hour < 11) return 'утро';
  if (hour >= 11 && hour < 17) return 'день';
  if (hour >= 17 && hour < 23) return 'вечер';
  return 'ночь';
}
