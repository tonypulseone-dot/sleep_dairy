/**
 * Слова, которые зависят от того, мальчик у мамы или девочка.
 *
 * Кнопка «Проснулся» у Мирославы — мелочь, которую мама видит по десять раз
 * в день, и каждый раз она говорит: приложение писали не про её ребёнка.
 * Пока род не указан, пишем в мужском роде — как о «малыше».
 */
export type ChildSex = 'boy' | 'girl';

export function childWords(sex: ChildSex | null | undefined) {
  const girl = sex === 'girl';
  return {
    fellAsleep: girl ? 'Уснула' : 'Уснул',
    wokeUp: girl ? 'Проснулась' : 'Проснулся',
    born: girl ? 'Родилась' : 'Родился',
    preterm: girl ? 'родилась раньше срока' : 'родился раньше срока',
    fullTerm: girl ? 'доношенная' : 'доношенный',
  };
}
