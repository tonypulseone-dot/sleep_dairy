/**
 * Реквизиты оператора персональных данных для политики конфиденциальности.
 *
 * ВНИМАНИЕ: до запуска на живых мамах эти поля должен заполнить владелец
 * приложения. По 152-ФЗ политика без названия оператора и способа связи
 * с ним юридической силы не имеет, поэтому страница /privacy показывает
 * заметное предупреждение, пока хоть одно поле пустое, — чтобы неполный
 * документ не уехал в продакшн незаметно.
 *
 * Значения задаются переменными окружения (LEGAL_*) и читаются на сервере
 * при каждом открытии страницы — менять реквизиты можно без пересборки.
 */
export const LEGAL = {
  /** Кто оператор: ФИО самозанятого, «ИП Иванов И. И.» или название ООО. */
  operator: process.env.LEGAL_OPERATOR ?? '',
  /** ИНН оператора. */
  inn: process.env.LEGAL_INN ?? '',
  /** Адрес, по которому мама может написать про свои данные. */
  email: process.env.LEGAL_EMAIL ?? '',
  /** Где физически стоит сервер с базой: город и хостинг-провайдер. */
  hosting: process.env.LEGAL_HOSTING ?? '',
} as const;

/** Дата последней редакции текста политики. Меняется вместе с текстом. */
export const POLICY_UPDATED = '24 сентября 2026 года';

/** Чего не хватает в реквизитах. Пустой массив — документ заполнен. */
export function legalGaps(): string[] {
  const gaps: string[] = [];
  if (!LEGAL.operator) gaps.push('кто оператор данных');
  if (!LEGAL.inn) gaps.push('ИНН оператора');
  if (!LEGAL.email) gaps.push('адрес для обращений');
  if (!LEGAL.hosting) gaps.push('где размещён сервер');
  return gaps;
}

/** Значение для текста политики: либо реквизит, либо явный пропуск. */
export function orGap(value: string, what: string): string {
  return value || `[не заполнено: ${what}]`;
}
