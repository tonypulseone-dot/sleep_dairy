async function main() {
  await db.delete(activities);
  for (const item of DRAFT) {
    await db.insert(activities).values({
      ageMonthsFrom: item.from,
      ageMonthsTo: item.to,
      title: item.title,
      body: item.body,
    });
  }
  console.log(`Загружено активностей: ${DRAFT.length} (черновик, ждёт замены от Виктории)`);
  process.exit(0);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
