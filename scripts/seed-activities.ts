function toItem(item: Item): ActivityItem {
  if (typeof item === 'string') return { body: item };
  return item[2] ? { title: item[0], sep: item[2], body: item[1] } : { title: item[0], body: item[1] };
}

async function main() {
  await db.delete(activityGroups);
  let total = 0;
  for (const [position, group] of GROUPS.entries()) {
    const sections: ActivitySection[] = group.sections.map((section) => ({
      title: section.title,
      ...(section.note ? { note: section.note } : {}),
      items: section.items.map(toItem),
    }));
    total += sections.reduce((sum, section) => sum + section.items.length, 0);
    await db.insert(activityGroups).values({
      position,
      title: group.title,
      ageMonthsFrom: group.from,
      ageMonthsTo: group.to,
      intro: group.intro ?? null,
      outro: group.outro ?? null,
      sections,
    });
  }
  console.log(`Загружено групп: ${GROUPS.length}, занятий: ${total}`);
  process.exit(0);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
