async function main() {
  await db.delete(activities);
  for (const item of ITEMS) {
    await db.insert(activities).values({
      ageMonthsFrom: item.from,
      ageMonthsTo: item.to,
      energy: item.energy,
      minutes: item.minutes,
      title: item.title,
      body: item.body,
    });
  }
  const byEnergy = ITEMS.reduce<Record<Energy, number>>(
    (acc, item) => ({ ...acc, [item.energy]: acc[item.energy] + 1 }),
    { active: 0, explore: 0, calm: 0 },
  );
  console.log(
    `Загружено занятий: ${ITEMS.length} (подвигаться ${byEnergy.active}, поиграть ${byEnergy.explore}, спокойно ${byEnergy.calm})`,
  );
  process.exit(0);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
