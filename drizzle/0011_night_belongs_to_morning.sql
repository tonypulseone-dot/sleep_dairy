-- Сутки по Виктории: ночной сон + бодрствование + дневные сны + бодрствование
-- до следующей ночи. Ночь с 26 на 27 теперь относится к суткам 27-го — к утру,
-- в которое закончилась, а не к вечеру, в который началась (см. sleepDayFor
-- в src/lib/sleep-day.ts). Раньше ночь лежала в сутках своего начала.
UPDATE "sleeps" SET "sleep_day" = "sleep_day" + 1 WHERE "kind" = 'night';
